/* 展开成 { 'YYYY-MM-DD': {kind:'legal'|'off'|'makeup', name:'春节'} } */
const CAL_INDEX = (() => {
  const idx = {};
  Object.keys(HOLIDAYS).forEach(y => {
    const year = HOLIDAYS[y];
    if (!year) return;
    Object.keys(year).forEach(name => {
      const h = year[name];
      h.off.forEach(d => { idx[d] = { kind:'off', name }; });
      h.legal.forEach(d => { idx[d] = { kind:'legal', name }; });
      h.makeup.forEach(d => { idx[d] = { kind:'makeup', name }; });
    });
  });
  return idx;
})();

